#!/usr/bin/env python3
"""Generates the KiCad projects from the board descriptions.

    python3 hardware/gen/generate.py [--symbols <KiCad symbols dir>] [--flat] [--out DIR] [boards]

writes hardware/pod_board/pod_board.kicad_sch (+ .kicad_pro) and the same for power_board.
A board with a drawing file (<board>_drawing.py) is drawn as a hierarchy of wired sheets
(kisheet.py); the others, or every board with --flat, as one sheet connected by net labels
(kisch.py). check.sh builds both for a drawn board and requires identical netlists.
Then run hardware/gen/check.sh: KiCad's ERC and the netlist cross-check (check_nets.py).
"""

import argparse
import importlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from kisch import Library, Schematic, layout  # noqa: E402
from kisheet import build_project  # noqa: E402

DEFAULT_SYMBOLS = "/mnt/c/Program Files/KiCad/10.0/share/kicad/symbols"


def project_file(name):
    """A minimal .kicad_pro: KiCad fills in the rest the first time it saves the project."""
    return {"meta": {"filename": f"{name}.kicad_pro", "version": 3},
            "schematic": {"legacy_lib_dir": "", "legacy_lib_list": []},
            "boards": [], "sheets": [], "text_variables": {}}


DATE = "2026-10-07"
COMMENT = "Generated by hardware/gen; see BUILD_GUIDE Part 4.8"


def build_drawn(m, drawing, lib, outdir):
    parts = {p["ref"]: p for _, ps, _ in m.groups for p in ps}
    sheets, root = drawing.draw(lib, parts)
    placed = {p.part["ref"] for s in sheets for p in s.placed}
    missing = sorted(set(parts) - placed)
    d = outdir / m.PROJECT
    d.mkdir(parents=True, exist_ok=True)
    for old in d.glob("*.kicad_sch"):  # sheets from an earlier drawing
        old.unlink()
    problems = build_project(lib, m.PROJECT, m.TITLE, sheets, root, d, DATE, COMMENT)
    problems += [("placement", f"{r} is not placed on any sheet") for r in missing]
    for where, what in problems:
        print(f"DRAWING PROBLEM ({where}): {what}")
    if problems:
        sys.exit(1)
    print(f"wrote {d}/{m.PROJECT}.kicad_sch and {len(sheets)} sheets")


def build(module, lib, outdir, flat=False):
    m = importlib.import_module(module)
    pro = outdir / m.PROJECT / f"{m.PROJECT}.kicad_pro"
    if not flat and (HERE / f"{module}_drawing.py").exists():
        build_drawn(m, importlib.import_module(f"{module}_drawing"), lib, outdir)
        if not pro.exists():
            pro.write_text(json.dumps(project_file(m.PROJECT), indent=2) + "\n")
        return
    sch = Schematic(lib, m.TITLE, m.PROJECT, rev="1", date=DATE, comment=COMMENT)
    layout(sch, m.groups, page_h=560)
    x = 20
    for net in m.POWER_FLAGS:
        sch.power_flag(net, x, 575)
        x += 15
    d = outdir / m.PROJECT
    d.mkdir(parents=True, exist_ok=True)
    sch.write(d / f"{m.PROJECT}.kicad_sch", paper="A1")
    if not pro.exists():
        pro.write_text(json.dumps(project_file(m.PROJECT), indent=2) + "\n")
    print(f"wrote {d}/{m.PROJECT}.kicad_sch")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", default=DEFAULT_SYMBOLS)
    ap.add_argument("--flat", action="store_true", help="label-only drawing for every board")
    ap.add_argument("--out", default=str(HERE.parent), help="output directory (default hardware/)")
    ap.add_argument("boards", nargs="*", default=["pod_board", "power_board"])
    a = ap.parse_args()
    lib = Library(a.symbols)
    for b in a.boards:
        build(b, lib, Path(a.out), a.flat)


if __name__ == "__main__":
    main()
