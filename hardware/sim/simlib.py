"""Shared helpers for the circuit simulations (WSL side): run netlists through KiCad's ngspice
(ngspice_run.py, in KiCad's Python) in parallel, and read ngspice's ASCII raw files."""

import os
import subprocess
import sys
from pathlib import Path

import numpy as np

SIM = Path(__file__).resolve().parent
ROOT = SIM.parent.parent
KICAD_PY = os.environ.get("KICAD_PY", "/mnt/c/Program Files/KiCad/10.0/bin/python.exe")


def win(p):
    return subprocess.run(["wslpath", "-w", str(p)], capture_output=True, text=True).stdout.strip()


def read_raw(path):
    """ngspice ASCII raw file -> {vector name (lower case): numpy array}."""
    text = Path(path).read_text(errors="replace").splitlines()
    names, i = [], 0
    while not text[i].startswith("Variables:"):
        i += 1
    i += 1
    while not text[i].startswith("Values:"):
        names.append(text[i].split()[1].lower())
        i += 1
    vals = [float(line.split()[-1]) for line in text[i + 1:] if line.strip()]
    n = len(names)
    data = np.array(vals[: (len(vals) // n) * n]).reshape(-1, n)
    return {name: data[:, k] for k, name in enumerate(names)}


def run_netlists(work, netlists, vectors):
    """netlists: {case name: netlist text}. Runs them in parallel; returns {case: vectors}."""
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    procs = {}
    for name, text in netlists.items():
        cir = work / f"{name}.cir"
        cir.write_text(text)
        procs[name] = subprocess.Popen(
            [KICAD_PY, win(SIM / "ngspice_run.py"), win(cir), win(work / f"{name}.raw"),
             win(work / f"{name}.log")] + vectors, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for name, p in procs.items():
        out = p.communicate()[0]
        if p.returncode:
            for q in procs.values():  # do not leave the other cases running
                if q.poll() is None:
                    q.kill()
            sys.exit(f"{name}: ngspice failed\n{out}\nsee {work / (name + '.log')}")
    return {name: read_raw(work / f"{name}.raw") for name in netlists}


def window(d, t0, t1):
    m = (d["time"] >= t0) & (d["time"] <= t1)
    return {k: v[m] for k, v in d.items()}


def results_table(title, intro, rows, ok, notes):
    """The results.md text: rows of (case, check, result, limit, PASS/FAIL/'')."""
    lines = ["<!-- Generated by the simulation script: do not edit. -->\n", f"# {title}\n",
             f"Overall: **{'ALL PASS' if ok else 'SOME FAIL'}**. {intro}\n",
             "| Case | Check | Result | Limit | |", "|---|---|---|---|---|"]
    lines += [f"| {c} | {w} | {v} | {lim} | {res} |" for c, w, v, lim, res in rows]
    return "\n".join(lines + [""] + notes) + "\n"
